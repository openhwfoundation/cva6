"""
Bitstream generation of the CVA6 Intel/Altera FPGA top level (Quartus).

The Intel counterpart of `vivado-fpga-build`, and a separate recipe rather
than an option of it: the two flows share no tool, no top level and no
project format. Quartus drives seven executables where Vivado drives one,
elaborates `cva6_altera` instead of `ariane_xilinx`, and takes its project
from a `.qsf` assembled out of CSV files instead of a TCL script.

Four stages:

- the **Platform Designer systems**, `interconnect` and `system` (which
  carries the HPS), generated by `qsys-script` + `qsys-generate`;
- the **project files**, `.qpf` and `.qsf`, written from the declarative
  CSV files of `corev_apu/altera/` (settings, pin locations, IO standards,
  IP files, search paths) plus the RTL filelist and the SDC constraints;
- the **nine IP cores**, generated by `qsys-script` then by
  `quartus_ipgenerate`;
- the **compilation** itself: `quartus_syn`, `quartus_fit`, `quartus_asm`
  and `quartus_sta`, then `quartus_pfg` for the raw binary file the HPS
  boots from.

The RTL comes from `config/target/<target>/Flist.cva6_altera`, so the file
list is data rather than code, and the CSV files are consumed as they are:
they hold 432 lines of board description that belong to the board, not to
a recipe.

Reports the resource usage and the timing slack as KPIs, checked against
`config/target/<target>/expected_values.yml` when the target carries
baselines for them.
"""

