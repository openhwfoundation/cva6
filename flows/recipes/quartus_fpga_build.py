app = typer.Typer()

# Resource deviation tolerance (%) vs
# config/target/<target>/expected_values.yml, like the Xilinx side: the
# fitter is directive driven and moves slightly between two runs.
DIFF_UTILIZATION = 2.0

# Project name of the Quartus flow, and so the basename of every file it
# produces. The same as corev_apu/altera/Makefile: the `.qsf` written
# below is read back by name by every quartus_* executable.
PROJECT = "Example-Project"

# CSV files of `corev_apu/altera/` feeding the `.qsf`, and the assignment
# each line becomes. They describe the board (66 settings, 270 pin
# locations, 74 IO standards...), so they are read as they are.
QSF_FROM_CSV = [
    ("settings.csv", "set_global_assignment -name {}"),
    ("loc_constraints.csv", "set_location_assignment {}"),
    ("io_standard_constraints.csv", "set_instance_assignment -name  {}"),
    ("ip_files.csv", "set_global_assignment -name IP_FILE {}"),
    ("search_paths.csv", "set_global_assignment -name SEARCH_PATH {}"),
]

# Quartus source assignment per file extension
QSF_SOURCE_TYPE = {
    ".vhd": "VHDL_FILE",
    ".v": "VERILOG_FILE",
    ".sv": "SYSTEMVERILOG_FILE",
    ".svh": "SYSTEMVERILOG_FILE",
}

# Compilation stages, in order. Each is a separate executable reading the
# project by name, and each can fail on its own.
QUARTUS_STAGES = [
    ("quartus_syn", "Synthesis", 7200),
    ("quartus_fit", "Fitter", 14400),
    ("quartus_asm", "Assembler", 3600),
]

# `quartus_syn` reports the resource usage in its own report file; the
# fitter refines it. Both are parsed the same way.
RESOURCE_RE = re.compile(
    r";\s*(?P<name>[\w /,()-]+?)\s*;\s*(?P<value>[\d,]+)\s*(?:/\s*[\d,]+\s*\(\s*"
    r"(?P<pct>[\d<>]+)\s*%\s*\))?\s*;"
)

# Worst case slack of `quartus_sta --do_report_timing`
SLACK_RE = re.compile(r"Slack\s*;\s*(-?\d+\.\d+)")


def _qsf_lines(altera_dir, report):
    """
    Return the `.qsf` assignments coming from the CSV board description.

    A missing CSV is fatal: the file holds the pinout or the device
    settings, and a project silently assembled without them would fit to
    the wrong pins.
    """
    lines = []
    for name, template in QSF_FROM_CSV:
        path = altera_dir / name
        if not path.exists():
            report.error_exit(f"Missing board description file: {path}", env=True)
        skipped = 0
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            # The device, the family and the top level come from the board
            # table: see ALTERA_QSF_OVERRIDDEN.
            if line.split(maxsplit=1)[0] in ALTERA_QSF_OVERRIDDEN:
                skipped += 1
                continue
            lines.append(template.format(line))
        if skipped:
            report.info(f"{name}: {skipped} assignment(s) taken from the board table")
        report.info(f"{name}: {len(lines)} assignment(s) so far")
    return lines


def _write_project(out_dir, altera_dir, params, rtl_files, bootrom_sv, report):
    """
    Write the `.qpf` and `.qsf` of the project.

    Written in one go, so a failed run cannot leave a half assembled
    project behind.
    """
    qpf = out_dir / f"{PROJECT}.qpf"
    qsf = out_dir / f"{PROJECT}.qsf"

    qpf.write_text(
        f'PROJECT_REVISION = "{PROJECT}"\n',
        encoding="utf-8",
    )

    lines = [
        "# Generated by ./cook.py quartus-fpga-build -- do not edit.",
        f"set_global_assignment -name TOP_LEVEL_ENTITY {ALTERA_TOP}",
        f"set_global_assignment -name DEVICE {params.device}",
        f'set_global_assignment -name FAMILY "{params.family}"',
    ]
    lines += _qsf_lines(altera_dir, report)

    # RTL, from the filelist plus the generated bootloader. Quartus wants
    # one assignment per file, typed by extension.
    sources = [Path(f) for f in rtl_files] + [Path(bootrom_sv)]
    for src in sources:
        kind = QSF_SOURCE_TYPE.get(src.suffix, "SOURCE_FILE")
        lines.append(f"set_global_assignment -name {kind} {src.as_posix()}")

    # Sources generated by Platform Designer: they only exist once the qsys
    # systems have been elaborated, so they are globbed here and not listed
    # in the filelist.
    generated = []
    for qsys in ALTERA_QSYS:
        for pattern in ("*.v", "*.sv", "*.svh"):
            generated += sorted((out_dir / qsys).rglob(pattern))
    for src in generated:
        kind = QSF_SOURCE_TYPE.get(src.suffix, "SOURCE_FILE")
        lines.append(f"set_global_assignment -name {kind} {src.as_posix()}")
    report.info(f"{len(generated)} file(s) generated by Platform Designer")

    sdc_files = sorted((altera_dir / "constraints").rglob("*.sdc"))
    if not sdc_files:
        report.error_exit(
            f"No SDC constraint in {altera_dir / 'constraints'}", env=True
        )
    for sdc in sdc_files:
        lines.append(f"set_global_assignment -name SDC_FILE {sdc.as_posix()}")

    qsf.write_text("\n".join(lines) + "\n", encoding="utf-8")
    report.info(f"project written: {qsf} ({len(lines)} assignments)")
    return qsf


def _report_resources(report, target, syn_rpt):
    """
    Record the resource usage and check it against the baseline.

    A report that cannot be parsed is a warning, never a failure: the
    bitstream is the deliverable, and a Quartus release changing the layout
    of its tables must not turn a good build red.
    """
    report.step("Resource usage")

    if not syn_rpt.exists():
        report.warning(f"{syn_rpt} missing, skipping resource reporting")
        return

    text = syn_rpt.read_text(encoding="utf-8", errors="replace")
    wanted = {
        "Logic utilization (in ALMs)": "alms",
        "Total registers": "registers",
        "Total block memory bits": "memory_bits",
        "Total DSP Blocks": "dsp",
        "Total pins": "pins",
    }
    found = {}
    for match in RESOURCE_RE.finditer(text):
        name = match.group("name").strip()
        if name in wanted and wanted[name] not in found:
            try:
                found[wanted[name]] = int(match.group("value").replace(",", ""))
            except ValueError:
                continue

    if not found:
        report.warning(f"No resource table found in {syn_rpt}")
        return

    report.metric("Resource usage", found)

    alms = found.get("alms")
    if alms is None:
        report.info("No ALM count in the report, skipping the utilization check")
        return

    report.set_label(f"{alms // 1000} kALMs")
    expected = read_config_expected_value(target, "altera_alms", report)
    report.kpi("altera_alms", alms, unit="ALMs", expected=expected, better="lower")
    for name, unit in (("registers", "FFs"), ("memory_bits", "bits")):
        if name in found:
            report.kpi(f"altera_{name}", found[name], unit=unit, better="lower")

    if expected is None:
        report.info("No expected ALM count available, skipping utilization check")
        return

    diff = (alms - int(expected)) / int(expected) * 100
    details = (
        f"Expected:  {expected} ALMs\n"
        f"Observed:  {alms} ALMs\n"
        f"Deviation: {diff:.2f} %"
    )
    if abs(diff) > DIFF_UTILIZATION:
        report.error(
            f"ALM count deviation limit exceeded (> {DIFF_UTILIZATION} %)\n\n{details}"
        )
    else:
        report.success(f"ALM count within limits.\n\n{details}")


def _report_timing(report, target, sta_rpt):
    """Record the worst slack and fail the build on a violation."""
    report.step("Timing")

    if not sta_rpt.exists():
        report.warning(f"{sta_rpt} missing, skipping timing reporting")
        return

    slacks = [
        float(s)
        for s in SLACK_RE.findall(sta_rpt.read_text(encoding="utf-8", errors="replace"))
    ]
    if not slacks:
        report.warning(f"No slack found in {sta_rpt}, skipping timing check")
        return

    wns = min(slacks)
    expected = read_config_expected_value(target, "altera_slack", report)
    report.kpi("altera_slack", wns, unit="ns", expected=expected, better="higher")
    report.metric("Timing", {"slack": wns, "paths": len(slacks)})

    if wns < 0:
        report.error(f"Timing not met: worst slack {wns} ns")
    else:
        report.success(f"Timing met: worst slack {wns} ns")


