@app.command()
def quartus_fpga_build(
    target: str = typer.Option(
        ...,
        "--target",
        "-t",
        help="CVA6 user configuration",
        autocompletion=autocompletion_target,
    ),
    board: AlteraBoard = typer.Option(AlteraBoard.agilex7, help="Altera FPGA board"),
    rbf: bool = typer.Option(
        True, help="Also generate the .rbf the HPS boots the fabric from"
    ),
    clean: bool = typer.Option(True, help="Clean working dir before"),
    quiet: bool = typer.Option(
        False, "--quiet", "-q", help="Suppress output (errors only)"
    ),
):
    """
    Quartus FPGA bitstream generation flow
    """
    report = RecipeReport(
        "quartus-fpga-build",
        title="QUARTUS FPGA BUILD",
        context={
            "target": target,
            "board": board,
            "rbf": rbf,
            "clean": clean,
        },
        quiet=quiet,
    )

    repo_dir = Path.cwd()
    altera_dir = repo_dir / "corev_apu" / "altera"
    out_dir = repo_dir / "build" / target / "fpga_altera" / board.value
    report.set_out_dir(out_dir)

    params = altera_board_params(board)
    report.add_context(
        {"device": params.device, "family": params.family, "dev_kit": params.dev_kit},
        table="Board parameters",
    )

    # ==========================================================
    # CHECK PREREQUISITES
    # ==========================================================
    report.step("Check prerequisites")

    # Seven executables, checked up front: a missing one three stages in
    # would waste an hour of fitting.
    tools = ["quartus_sh", "quartus_syn", "quartus_fit", "quartus_asm", "quartus_sta"]
    if rbf:
        tools.append("quartus_pfg")
    tools += ["quartus_ipgenerate", "qsys-script", "qsys-generate"]
    for tool in tools:
        path = shutil.which(tool)
        if path is None:
            report.error_exit(
                f"{tool}: Not found\n"
                f"  The Altera flow needs Quartus Prime Pro in PATH "
                f"(qsys-script and qsys-generate live in its sopc_builder/bin).",
                env=True,
            )
        report.success(f"{tool}: {path}")

    xlen = _xlen(target, report)
    bootrom_dir = repo_dir / "build" / "bootrom" / board.value
    bootrom_sv = bootrom_dir / f"bootrom_{xlen}.sv"
    report.add_context({"xlen": xlen})

    require_prerequisite(
        bootrom_sv,
        f"zero stage bootloader of board '{board.value}' (RV{xlen})",
        f"./cook.py fpga-bootrom -t {target} -c <toolchain> --board {board.value}",
        report=report,
    )
    require_manifest_option(
        read_manifest(bootrom_dir, report),
        "board",
        [board.value],
        f"the bitstream of board '{board.value}' needs a bootloader built for it",
        f"./cook.py fpga-bootrom -t {target} -c <toolchain> --board {board.value}",
        report=report,
        manifest_dir=bootrom_dir,
    )

    # The HPS boots from this preloader image, which is a prebuilt blob of
    # the repository rather than something the flow produces.
    hps_hex = altera_dir / "u-boot-spl-dtb.hex"
    if rbf and not hps_hex.exists():
        report.error_exit(
            f"Missing HPS preloader {hps_hex}\n"
            f"  It is the u-boot SPL the .rbf embeds: pass --no-rbf to stop "
            f"after the .sof, or restore the file.",
            env=True,
        )

    report.success("Prerequisites OK")

    # ==========================================================
    # CLEAN
    # ==========================================================
    report.step("Clean")
    if clean:
        try:
            if out_dir.exists():
                shutil.rmtree(out_dir)
                report.info(f"remove {out_dir}")
        except OSError as e:
            report.error_exit(f"Clean error : {e}", env=True)
    else:
        report.info(f"Skip cleaning {out_dir}")

    out_dir.mkdir(parents=True, exist_ok=True)
    report.info(f"create {out_dir}")

    # ==========================================================
    # PLATFORM DESIGNER SYSTEMS
    # ==========================================================
    # `interconnect` and `system` are Platform Designer systems, not plain
    # IPs: they are elaborated first because the project reads the RTL they
    # generate. The HPS lives in `system`.
    report.step("Generate Platform Designer systems")

    qsys_results = report.metric("Platform Designer")
    for qsys, script in ALTERA_QSYS.items():
        script_path = altera_dir / "ip" / script
        if not script_path.exists():
            report.error_exit(f"Missing qsys script: {script_path}", env=True)
        for stage, cmd in (
            ("script", ["qsys-script", f"--script={script_path}"]),
            (
                "generate",
                [
                    "qsys-generate",
                    f"{qsys}.qsys",
                    f"--quartus-project={altera_dir / 'ip' / Path(script).stem}",
                    "--synthesis",
                ],
            ),
        ):
            run_cmd(
                cmd=cmd,
                report=report,
                cwd=out_dir,
                env=None,
                error_patterns=["^Error|Error:"],
                warning_patterns=["^Warning|Warning:"],
                highlight_patterns=None,
                log_file=out_dir / f"qsys_{qsys}_{stage}.log",
                timeout=3600,
                check=False,
                capture_output=False,
            )
        ok = (out_dir / qsys).is_dir()
        qsys_results.add_row(
            status="pass" if ok else "fail",
            system=qsys,
            state="generated" if ok else "missing",
        )
    report.print_metric(qsys_results)
    if qsys_results.failed:
        report.error_exit("Platform Designer generation failed")

    # ==========================================================
    # PROJECT FILES
    # ==========================================================
    report.step("Write project files")

    rtl_files = read_config_or_exit_flist(
        target, report, filename="Flist.cva6_altera", repo_dir=repo_dir
    )
    report.info(f"{len(rtl_files)} RTL file(s) read from Flist.cva6_altera")

    qsf = _write_project(out_dir, altera_dir, params, rtl_files, bootrom_sv, report)

    # ==========================================================
    # IP CORES
    # ==========================================================
    report.step("Generate IP cores")

    ip_results = report.metric("IP cores")
    for ip_script in ALTERA_IPS:
        script_path = altera_dir / "ip" / ip_script
        if not script_path.exists():
            report.error_exit(f"Missing IP script: {script_path}", env=True)
        run_cmd(
            cmd=["qsys-script", f"--script={script_path}"],
            report=report,
            cwd=out_dir,
            env=None,
            error_patterns=["^Error|Error:"],
            warning_patterns=["^Warning|Warning:"],
            highlight_patterns=None,
            log_file=out_dir / f"ip_{Path(ip_script).stem}.log",
            timeout=1800,
            check=False,
            capture_output=False,
        )
        ip_file = out_dir / f"{Path(ip_script).stem}.ip"
        ip_results.add_row(
            status="pass" if ip_file.exists() else "fail",
            ip=Path(ip_script).stem,
            state="generated" if ip_file.exists() else "missing",
        )
    report.print_metric(ip_results)
    if ip_results.failed:
        report.error_exit("IP core generation failed")

    run_cmd(
        cmd=["quartus_ipgenerate", "--generate_project_ip_files", PROJECT],
        report=report,
        cwd=out_dir,
        env=None,
        error_patterns=["^Error|Error \\("],
        warning_patterns=["^Warning"],
        highlight_patterns=None,
        log_file=out_dir / "ipgenerate.log",
        timeout=3600,
        check=False,
        capture_output=False,
    )
    report.success(f"{len(ALTERA_IPS)} IP core(s) generated")

    # ==========================================================
    # COMPILATION
    # ==========================================================
    # One executable per stage, each reading the project by name. They are
    # run in sequence and the first failure stops the build: fitting a
    # design whose synthesis failed only produces a second error.
    for tool, stage, timeout in QUARTUS_STAGES:
        report.step(stage)
        log_file = out_dir / f"{tool}.log"
        run_cmd(
            cmd=[tool, PROJECT],
            report=report,
            cwd=out_dir,
            env=None,
            error_patterns=["^Error|Error \\("],
            warning_patterns=["^Critical Warning"],
            highlight_patterns=["^Info: Quartus"],
            log_file=log_file,
            timeout=timeout,
            check=False,
            capture_output=False,
        )
        n_err, _ = report.analyze_log(
            log_file,
            name=f"{tool}.log analysis",
            error_patterns=["^Error", "Error \\("],
            warning_patterns=["^Critical Warning"],
            env_patterns=[
                r"(license|licence).*(error|fail|unable|denied|expired)",
                r"unable to checkout",
                r"command not found",
                r"No license",
            ],
            fail_on_error=False,
        )
        if n_err:
            report.error_exit(f"{stage} failed: {n_err} error(s) in {log_file}")
        report.success(f"{stage} completed")

    # Timing analysis: reported but run as its own stage, since its report
    # is what the timing check below reads.
    report.step("Timing analysis")
    run_cmd(
        cmd=["quartus_sta", PROJECT, "--do_report_timing"],
        report=report,
        cwd=out_dir,
        env=None,
        error_patterns=["^Error|Error \\("],
        warning_patterns=["^Critical Warning"],
        highlight_patterns=None,
        log_file=out_dir / "quartus_sta.log",
        timeout=3600,
        check=False,
        capture_output=False,
    )

    sof_files = sorted((out_dir / "output_files").glob("*.sof"))
    if not sof_files:
        report.error_exit(f"Bitstream not generated in {out_dir / 'output_files'}")
    sof_file = sof_files[0]
    report.success(f"Bitstream generated: {sof_file}")

    # ==========================================================
    # HPS BOOT IMAGE
    # ==========================================================
    # The Agilex fabric is configured by the HPS, which needs the raw binary
    # form of the bitstream with the u-boot SPL embedded in it.
    rbf_file = out_dir / "output_files" / "cva6-hps.rbf"
    if rbf:
        report.step("Generate HPS boot image")
        run_cmd(
            cmd=[
                "quartus_pfg",
                "-c",
                str(sof_file),
                str(rbf_file),
                "-o",
                f"hps_path={hps_hex}",
            ],
            report=report,
            cwd=out_dir,
            env=None,
            error_patterns=["^Error|Error \\("],
            warning_patterns=["^Warning"],
            highlight_patterns=None,
            log_file=out_dir / "quartus_pfg.log",
            timeout=1800,
            check=False,
            capture_output=False,
        )
        if rbf_file.exists():
            report.success(f"HPS boot image generated: {rbf_file}")
        else:
            report.error(f"HPS boot image not generated: {rbf_file}")

    # ==========================================================
    # REPORTING
    # ==========================================================
    _report_resources(report, target, out_dir / f"{PROJECT}.syn.rpt")
    _report_timing(report, target, out_dir / f"{PROJECT}.sta.rpt")

    # ==========================================================
    # BUILD MANIFEST
    # ==========================================================
    write_manifest(
        out_dir,
        "quartus-fpga-build",
        {
            "target": target,
            "board": board,
            "xlen": xlen,
            "device": params.device,
            "family": params.family,
            "bootrom_sv": str(bootrom_sv.relative_to(repo_dir)),
            "rbf": rbf,
            "sof": str(sof_file.relative_to(repo_dir)),
        },
        report=report,
    )

    # ==========================================================
    # List
    # ==========================================================
    report.step("Generated files")
    gen_files = [
        sof_file,
        rbf_file,
        qsf,
        out_dir / f"{PROJECT}.qpf",
        out_dir / f"{PROJECT}.syn.rpt",
        out_dir / f"{PROJECT}.fit.rpt",
        out_dir / f"{PROJECT}.asm.rpt",
        out_dir / f"{PROJECT}.sta.rpt",
    ]
    generated = []
    for genfile in gen_files:
        if genfile.exists():
            report.info(f"> {genfile}")
            generated.append(str(genfile.relative_to(repo_dir)))

    # ==========================================================
    # BUILD REPORT
    # ==========================================================
    report.log("Generated files", generated)

    report.end("Completed")


def _xlen(target, report):
    """
    Return the register width the target is built for.

    Read from the ISA the software is compiled with rather than guessed
    from the target name, like the Xilinx recipe does.
    """
    march, _ = read_config_or_exit_isa(target, report)
    if march.startswith("rv64"):
        return 64
    if march.startswith("rv32"):
        return 32
    return report.error_exit(
        f"Cannot tell the register width from march {march!r} of target "
        f"'{target}': expected it to start with rv32 or rv64",
        env=True,
    )
