"""
Build manifest utilities.

Each recipe that generates artifacts in the build tree writes a
`cook_manifest.yml` file in its output directory. The manifest records the
recipe name and the options used to generate the artifacts.

Recipes that depend on those artifacts can then:
- check that the prerequisite artifacts exist and get an actionable
  message telling the user which recipe to run first (require_prerequisite)
- read the manifest and check that the options used by the producer recipe
  are compatible with the options requested now (require_manifest_option)

All functions take the RecipeReport of the calling recipe: messages are
printed (respecting report.quiet) and recorded in the report; fatal
checks go through report.error_exit() so the report is written before
exiting.
"""

from datetime import datetime
from enum import Enum
from pathlib import Path
import yaml

MANIFEST_NAME = "cook_manifest.yml"


def _serialize(value):
    """Convert option values to plain YAML-friendly types."""
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, (list, tuple)):
        return [_serialize(v) for v in value]
    if isinstance(value, dict):
        return {k: _serialize(v) for k, v in value.items()}
    # `typer.Option(x)` is a descriptor holding x, not x itself, and Typer only
    # swaps it for the value it carries when it parses the command line. A
    # recipe called as a plain function, which is how the patterns and the
    # macros call them, therefore receives that descriptor for every option the
    # caller left out: such a caller has to pass them explicitly.
    #
    # The descriptor is not serializable, and write_manifest dumps before
    # writing, so letting it through means no manifest at all and a
    # prerequisite check downstream with nothing to read. Name the option
    # instead, the manifest stays readable and the faulty call is visible.
    if type(value).__name__ in ("OptionInfo", "ArgumentInfo"):
        return f"<unset typer default: {type(value).__name__}>"
    return value


def write_manifest(out_dir, recipe, options, report):
    """
    Write the build manifest describing how `out_dir` was generated.

    Args:
        out_dir: output directory of the recipe (Path)
        recipe: cook.py recipe name (e.g. "vcs-uvm-comp")
        options: dict of the options used by the recipe
        report: RecipeReport of the calling recipe
    """
    manifest_path = Path(out_dir) / MANIFEST_NAME
    data = {
        "recipe": recipe,
        "date": datetime.now().isoformat(timespec="seconds"),
        "options": _serialize(options),
    }
    # Serialize first: a dump failing halfway through would otherwise
    # leave a truncated (or empty) manifest behind, which downstream
    # recipes would read as "no option recorded".
    try:
        content = yaml.safe_dump(data, sort_keys=False, default_flow_style=False)
    except yaml.YAMLError as e:
        report.warning(f"Could not serialize manifest {manifest_path}: {e}")
        return
    try:
        manifest_path.write_text(content, encoding="utf-8")
        report.info(f"manifest written: {manifest_path}")
    except OSError as e:
        report.warning(f"Could not write manifest {manifest_path}: {e}")


def read_manifest(out_dir, report):
    """
    Read the build manifest of `out_dir`.

    Returns the manifest dict, or None if the manifest is missing or
    unreadable (e.g. artifacts generated by an older version of cook.py).

    Args:
        out_dir: producer output directory (Path)
        report: RecipeReport of the calling recipe
    """
    manifest_path = Path(out_dir) / MANIFEST_NAME
    if not manifest_path.exists():
        return None
    try:
        with manifest_path.open("r", encoding="utf-8") as f:
            return yaml.safe_load(f)
    except Exception as e:
        report.warning(f"Could not read manifest {manifest_path}: {e}")
        return None


def require_prerequisite(path, description, hint, report):
    """
    Check that a prerequisite artifact exists.

    Exits with an actionable error message (recorded as an environment
    failure in the report) telling the user which recipe to run first if
    the artifact is missing.

    Args:
        path: artifact path expected to exist (file or directory)
        description: human-readable description of the artifact
        hint: example cook.py command generating the artifact
        report: RecipeReport of the calling recipe
    """
    path = Path(path)
    if not path.exists():
        report.error_exit(
            f"Missing prerequisite: {description}\n"
            f"  Expected: {path}\n"
            f"  Run first: {hint}",
            env=True,
        )


def get_manifest_option(manifest, option, default=None):
    """Return an option recorded in a manifest, or `default` if absent."""
    if not manifest:
        return default
    return manifest.get("options", {}).get(option, default)


def require_manifest_option(
    manifest,
    option,
    allowed,
    requirement,
    hint,
    report,
    manifest_dir=None,
):
    """
    Check that an option recorded in a producer manifest is compatible
    with the options requested now. Exits (environment failure recorded
    in the report) with an explanation if not.

    If the manifest is missing (artifacts generated by an older cook.py),
    only a warning is emitted and the check is skipped.

    Args:
        manifest: manifest dict returned by read_manifest() (or None)
        option: option name recorded in the producer manifest
        allowed: list of accepted values for this option
        requirement: human-readable description of the incompatibility
        hint: example cook.py command fixing the problem
        report: RecipeReport of the calling recipe
        manifest_dir: producer output dir (for warning message only)
    """
    if manifest is None:
        where = f" in {manifest_dir}" if manifest_dir else ""
        report.warning(
            f"No manifest found{where} (generated by an older cook.py?), skipping compatibility check for '{option}'"
        )
        return
    value = get_manifest_option(manifest, option)
    if value not in allowed:
        producer = manifest.get("recipe", "producer recipe")
        report.error_exit(
            f"Incompatible option: {requirement}\n"
            f"  '{producer}' was run with {option}={value!r}, "
            f"expected one of {[_serialize(a) for a in allowed]}\n"
            f"  Fix: {hint}",
            env=True,
        )
